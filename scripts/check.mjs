import assert from 'node:assert/strict';
import { readFile, readdir, stat } from 'node:fs/promises';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import vm from 'node:vm';
const root=resolve(dirname(fileURLToPath(import.meta.url)),'..');
const read=name=>readFile(resolve(root,name),'utf8');
const [html,app,data,preview,css]=await Promise.all(['index.html','app.js','data.js','preview.js','styles.css'].map(read));
for(const [name,source] of [['app.js',app],['data.js',data],['preview.js',preview]])new vm.Script(source,{filename:name});
const context={window:{}};vm.runInNewContext(data,context);const report=context.window.UVA_REPORT;
assert.equal(report.chapters.length,13);assert.ok(!('spreads' in report));
assert.match(html,/noindex, nofollow, noarchive/);assert.match(html,/preview\.js/);
assert.ok(!/<script[^>]+src="(?:app|data)\.js"/.test(html),'Report scripts should load through the preview entrance');
for(const token of ['bookEdition','bookFurniture','chapterRail','data-rail','original-report'])assert.ok(!app.includes(token),`Discarded feature: ${token}`);
for(const token of ['data-edition','data-navigation="note"','data-navigation="cinema"','.chapter-rail'])assert.ok(!css.includes(token),`Discarded styles: ${token}`);
const media=[...new Set((app+data).match(/p\d{2}-\d{2}/g))].sort();
for(const name of media)assert.ok((await stat(resolve(root,'assets/media',name+'.webp'))).size>0);
assert.equal((await readdir(resolve(root,'assets/media'))).filter(x=>x.endsWith('.webp')).length,media.length,'Unreferenced images remain');
for(const name of ['assets/ImpactReport26_Complete.pdf','favicon.svg','robots.txt'])assert.ok((await stat(resolve(root,name))).size>0);
for(const chapter of report.chapters)assert.ok(app.includes(`id="${chapter.id}"`),`Missing chapter ${chapter.id}`);
const files=await readdir(root);assert.ok(!files.some(f=>/^option-.*\.html$/.test(f)||f==='navigation-options.html'),'Design studies remain in source');
console.log(`PASS: Folio-only source, 13 chapters, ${media.length} image references, preview entrance, source PDF and indexing controls.`);
